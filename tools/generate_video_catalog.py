"""Embed validated JSON catalogues for portable, cwd-independent builds."""
import argparse
import json
from pathlib import Path
from validate_video_catalog import load, read_json, validate, validate_machine_options

ROOT=Path(__file__).resolve().parents[1]
FILES=('video_devices.json','video_output_capabilities.json','video_output_profiles.json','video_machine_options.json')

def generate():
    data=load(ROOT/'src');validate(*data)
    machine=read_json(ROOT/'src'/FILES[3]);validate_machine_options(machine,data[0],data[2])
    result='// Generated by tools/generate_video_catalog.py. Edit src/video_*.json.\n#pragma once\nnamespace VideoCatalogData {\n'
    for key,name in zip(('devices','capabilities','profiles','machines'),FILES):
        content=json.dumps(read_json(ROOT/'src'/name),separators=(',',':'))
        result+=f'inline constexpr char {key}[] = R"VCATALOG({content})VCATALOG";\n'
    return result+'}\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'src/VideoCatalogData.h';text=generate()
    if args.check:
        if not path.exists() or path.read_text()!=text: raise SystemExit('VideoCatalogData.h is stale; run tools/generate_video_catalog.py')
    elif not path.exists() or path.read_text()!=text:path.write_text(text)
