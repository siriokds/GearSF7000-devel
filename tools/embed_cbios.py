"""Generate the embedded firmware header from the licensed C-BIOS images."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
images = {"MainNTSC": "cbios_main_msx1.rom", "MainPAL": "cbios_main_msx1_eu.rom", "Logo": "cbios_logo_msx1.rom"}
lines = ["// Generated by tools/embed_cbios.py; see third_party/cbios/LICENSE.txt.", "#pragma once", "namespace CBios {"]
for name, file in images.items():
    data = (root / "third_party/cbios" / file).read_bytes()
    lines.append(f"inline constexpr unsigned char {name}[] = {{")
    lines.extend("    " + ",".join(f"0x{b:02x}" for b in data[i:i+16]) + "," for i in range(0, len(data), 16))
    lines.append("};")
license_text = (root / "third_party/cbios/LICENSE.txt").read_text()
lines.append('inline constexpr char License[] = R"CBIOSLICENSE(' + license_text + ')CBIOSLICENSE";')
lines.append("}")
(root / "src/CBiosData.h").write_text("\n".join(lines) + "\n")
