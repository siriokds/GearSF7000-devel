// Splits a translation-map index into the matrix position it stands for.
static inline void SK1100_TranslationIndexToPosition(int index, int* row, int* mask)
{
    if (index < 56)
    {
        *row = index / 8;
        *mask = 1 << (index % 8);
    }
    else
    {
        *row = 63 - index;
        *mask = 256;
    }
}

