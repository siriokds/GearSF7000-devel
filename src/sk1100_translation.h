// The SC-3000 BASIC keyboard translation maps, transcribed from the ROM at
// $3FA0-$4120. These are what the machine itself uses to turn a matrix
// position into a character code, so they are the authority on what can be
// typed - guessing from a keyboard photograph gets the graphic set wrong, and
// got the Yen key's position wrong here for a while.
//
// Generated from DOCS/SC3000_BASIC_TRANSLATION_MAPS.asm, which is the
// disassembly those bytes came from, including the ROM's own notes on how it
// chooses between the maps. Regenerate from there rather than editing here.
//
// Each map is indexed by the column-major physical-key index the matrix scan
// produces. Entries 0-55 are rows 0-6 over masks 1..128; entries 56-63 are the
// mask-256 column in *reverse* row order, which is why index 63 is row 0.
// SK1100_TranslationIndexToPosition() below is the only place that knows this.
//
// Map selection, per the ROM's own dispatch order: FUNC (macro path, no map),
// CTRL, ENG/DIER, then the editor's persistent Latin/GRAPH state, then SHIFT.
// GRAPH is not a held modifier - it is a mode the GRAPH key toggles, and the
// prompt cursor changes to an asterisk while it is active.
//
// The CTRL map is not transcribed: it produces editing control codes, not text.

